// Built-in 1-bit monochrome icon library for Macropad Studio (16x16 pixels)
const { packBitsToBitmap, bitmapToHex } = require("./image-converter");

function patternToHex(pattern) {
  const bits = new Uint8Array(16 * 16);
  for (let y = 0; y < 16; y++) {
    for (let x = 0; x < 16; x++) {
      bits[y * 16 + x] = pattern[y][x] === "#" ? 1 : 0;
    }
  }
  return bitmapToHex(packBitsToBitmap(bits, 16, 16));
}

