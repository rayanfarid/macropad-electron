const BUILTIN_ICONS = ICONS_SPEC.map(spec => ({
  id: spec.id,
  name: spec.name,
  width: 16,
  height: 16,
  bitmap: patternToHex(spec.pattern)
}));

const ICONS_BY_ID = new Map();
for (const icon of BUILTIN_ICONS) {
  ICONS_BY_ID.set(icon.id, icon);
  ICONS_BY_ID.set(icon.name.toLowerCase(), icon);
}
// Also map aliases like "chatgpt", "ai", "selectall"
ICONS_BY_ID.set("chatgpt", ICONS_BY_ID.get("chatgpt-ai"));
ICONS_BY_ID.set("ai", ICONS_BY_ID.get("chatgpt-ai"));
ICONS_BY_ID.set("chatgpt/ai", ICONS_BY_ID.get("chatgpt-ai"));
ICONS_BY_ID.set("chatgpt / ai", ICONS_BY_ID.get("chatgpt-ai"));
ICONS_BY_ID.set("selectall", ICONS_BY_ID.get("select-all"));

function getBuiltinIcon(id) {
  if (!id || typeof id !== "string") return null;
  const key = id.toLowerCase().trim();
  if (ICONS_BY_ID.has(key)) return ICONS_BY_ID.get(key);
  const normalized = key.replace(/[\s_/]+/g, "-");
  if (ICONS_BY_ID.has(normalized)) return ICONS_BY_ID.get(normalized);
  const stripped = key.replace(/[\s_\/-]+/g, "");
  return ICONS_BY_ID.get(stripped) || null;
}

function getAllBuiltinIcons() {
  return BUILTIN_ICONS.slice();
}

module.exports = {
  BUILTIN_ICONS,
  getBuiltinIcon,
  getAllBuiltinIcons
};
